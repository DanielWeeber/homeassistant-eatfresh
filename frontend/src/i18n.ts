export type Lang = "de" | "en";

export function pickLang(language: string | undefined): Lang {
  return (language ?? "").toLowerCase().startsWith("de") ? "de" : "en";
}

/** True if a text with this key exists. */
export function hasText(key: string): key is StringKey {
  return Object.prototype.hasOwnProperty.call(de, key);
}

export function translate(
  lang: Lang,
  key: StringKey,
  vars: Record<string, string | number> = {},
): string {
  const text = (lang === "de" ? de : en)[key];
  return text.replace(/\{(\w+)\}/g, (_m, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}
